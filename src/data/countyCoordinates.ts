/**
 * Get state abbreviation from full name
 */
export function getStateAbbreviation(state: string): string {
  if (!state) return ''
  // Already an abbreviation
  if (state.length === 2) return state.toUpperCase()
  return STATE_ABBREVIATIONS[state] || state
}

/**
 * Get coordinates for a county
 */
export function getCountyCoordinates(state: string, county: string): Coordinates | null {
  if (!state || !county) return null
  const stateAbbr = getStateAbbreviation(state)
  const key = `${stateAbbr}:${county}`
  return COUNTY_COORDINATES[key] || null
}

/**
 * Calculate distance between two coordinates using Haversine formula
 * Returns distance in miles
 */
export function calculateDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 3959 // Earth's radius in miles
  const dLat = (lat2 - lat1) * Math.PI / 180
  const dLon = (lon2 - lon1) * Math.PI / 180
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2)
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a))
  return R * c
}

/**
 * Get distance from a home location to a listing's county
 * Returns distance in miles, or null if coordinates not found
 */
export function getDistanceToCounty(
  homeState: string,
  homeCounty: string,
  listingState: string,
  listingCounty: string
): number | null {
  const homeCoords = getCountyCoordinates(homeState, homeCounty)
  const listingCoords = getCountyCoordinates(listingState, listingCounty)

  if (!homeCoords || !listingCoords) return null

  return calculateDistance(
    homeCoords.latitude,
    homeCoords.longitude,
    listingCoords.latitude,
    listingCoords.longitude
  )
}

